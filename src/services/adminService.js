import { httpAdapter } from '../adapters/httpAdapter.js';

/** Operaciones REST de administración, talleres, clientes, visitas y estado vehicular. */
export const adminService = {
  performanceMetrics: () => httpAdapter.get('/admin/performance'),
  recordPerformancePage: (data) => httpAdapter.post('/admin/performance/pages', data),
  users: () => httpAdapter.get('/admin/users'),
  createUser: (data) => httpAdapter.post('/admin/users', data),
  updateUser: (id, data) => httpAdapter.patch(`/admin/users/${encodeURIComponent(id)}`, data),
  setUserStatus: (id, status) => httpAdapter.patch(`/admin/users/${encodeURIComponent(id)}/status`, { status }),
  roles: () => httpAdapter.get('/admin/roles'),
  createRole: (data) => httpAdapter.post('/admin/roles', data),
  updateRole: (id, data) => httpAdapter.patch(`/admin/roles/${encodeURIComponent(id)}`, data),
  setRoleStatus: (id, status) => httpAdapter.patch(`/admin/roles/${encodeURIComponent(id)}/status`, { status }),
  assignments: () => httpAdapter.get('/admin/role-assignments'),
  assignRole: (userId, roleId) => httpAdapter.post('/admin/role-assignments', { userId, roleId }),
  removeAssignment: (assignmentId) => httpAdapter.delete(`/admin/role-assignments/${encodeURIComponent(assignmentId)}`),
  workshops: () => httpAdapter.get('/admin/workshops'),
  uploadWorkshopPhoto: (image) => httpAdapter.post('/admin/workshops/photo', image),
  createWorkshop: (data) => httpAdapter.post('/admin/workshops', data),
  setWorkshopStatus: (id, status) => httpAdapter.patch(`/admin/workshops/${encodeURIComponent(id)}/status`, { status }),
  lookupAddress: (query) => httpAdapter.get(`/admin/address-lookup?${new URLSearchParams(query)}`),
  clients: (params = {}) => httpAdapter.get(`/admin/clients?${new URLSearchParams(params)}`),
  createClient: (data) => httpAdapter.post('/admin/clients', data),
  updateClient: (id, data) => httpAdapter.patch(`/admin/clients/${encodeURIComponent(id)}`, data),
  setClientStatus: (id, status) => httpAdapter.patch(`/admin/clients/${encodeURIComponent(id)}/status`, { status }),
  visits: () => httpAdapter.get('/admin/visits'),
  recordVisit: (data) => httpAdapter.post('/admin/visits', data),
  vehicles: () => httpAdapter.get('/admin/vehicles'),
  uploadVehiclePhoto: (image) => httpAdapter.post('/admin/vehicles/photos', image),
  createVehicle: (data) => httpAdapter.post('/admin/vehicles', data),
  updateVehicle: (id, data) => httpAdapter.patch(`/admin/vehicles/${encodeURIComponent(id)}`, data),
  setVehicleStatus: (id, status) => httpAdapter.patch(`/admin/vehicles/${encodeURIComponent(id)}/status`, { status }),
  associateVehicleClient: (id, customerId) => httpAdapter.post(`/admin/vehicles/${encodeURIComponent(id)}/associate-client`, { customerId }),
  setVehicleRepairStatus: (id, data) => httpAdapter.post(`/admin/vehicles/${encodeURIComponent(id)}/repair-status`, data),
  customerVehicleStatus: () => httpAdapter.get('/customer/vehicle-status'),
};
