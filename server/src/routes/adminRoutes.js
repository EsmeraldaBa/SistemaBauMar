import { Router } from 'express';
import { asyncHandler } from '../utils/asyncHandler.js';
import { authenticate, requireAdministrator, requireAnyRole } from '../middleware/auth.js';
import * as admin from '../controllers/adminController.js';
import * as workshop from '../controllers/workshopController.js';

const router = Router();
router.use(authenticate);
router.get('/performance', requireAdministrator, asyncHandler(admin.getPerformanceReport));
router.post('/performance/pages', requireAdministrator, asyncHandler(admin.recordPerformancePage));
// El directorio es visible con sesión; los datos de contacto se reservan al administrador.
router.get('/users', asyncHandler(admin.getUsers));
router.post('/users', requireAdministrator, asyncHandler(admin.postUser));
router.patch('/users/:userId', requireAdministrator, asyncHandler(admin.patchUser));
router.patch('/users/:userId/status', requireAdministrator, asyncHandler(admin.patchUserStatus));
router.get('/roles', asyncHandler(admin.getRoles));
router.post('/roles', requireAdministrator, asyncHandler(admin.postRole));
router.patch('/roles/:roleId', requireAdministrator, asyncHandler(admin.patchRole));
router.patch('/roles/:roleId/status', requireAdministrator, asyncHandler(admin.patchRoleStatus));
router.get('/role-assignments', requireAdministrator, asyncHandler(admin.getRoleAssignments));
router.post('/role-assignments', requireAdministrator, asyncHandler(admin.postRoleAssignment));
router.delete('/role-assignments/:assignmentId', requireAdministrator, asyncHandler(admin.deleteRoleAssignment));
router.get('/address-lookup', requireAdministrator, asyncHandler(workshop.lookupAddress));
router.post('/workshops/photo', requireAdministrator, asyncHandler(workshop.uploadWorkshopPhoto));
router.get('/workshops', asyncHandler(workshop.listWorkshops));
router.post('/workshops', requireAdministrator, asyncHandler(workshop.createWorkshop));
router.patch('/workshops/:workshopId/status', requireAdministrator, asyncHandler(workshop.setWorkshopStatus));
router.get('/clients', asyncHandler(workshop.listCustomers));
router.post('/clients', requireAnyRole('administrator','receptionist'), asyncHandler(workshop.createCustomer));
router.patch('/clients/:customerId', requireAnyRole('administrator','receptionist'), asyncHandler(workshop.updateCustomer));
router.patch('/clients/:customerId/status', requireAdministrator, asyncHandler(workshop.setCustomerStatus));
router.get('/visits', asyncHandler(workshop.listWorkshopVisits));
router.post('/visits', requireAnyRole('administrator','receptionist'), asyncHandler(workshop.recordWorkshopVisit));
router.post('/vehicles/photos', requireAnyRole('administrator','receptionist'), asyncHandler(workshop.uploadVehiclePhoto));
router.post('/vehicles', requireAnyRole('administrator','receptionist'), asyncHandler(workshop.createVehicle));
router.get('/vehicles', asyncHandler(workshop.listVehicles));
router.patch('/vehicles/:vehicleId', requireAnyRole('administrator','receptionist'), asyncHandler(workshop.updateVehicle));
router.patch('/vehicles/:vehicleId/status', requireAnyRole('administrator','receptionist'), asyncHandler(workshop.setVehicleLifecycleStatus));
router.post('/vehicles/:vehicleId/associate-client', requireAnyRole('administrator','receptionist'), asyncHandler(workshop.associateVehicleClient));
router.post('/vehicles/:vehicleId/repair-status', requireAnyRole('administrator','technician'), asyncHandler(workshop.addVehicleStatus));
export default router;
